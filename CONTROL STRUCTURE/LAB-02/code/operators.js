let num1 = 6 //assigning value to num1
let num2 = 5 //assigning value to num2

let sum = num1 + num2 //adding num1 and num2 and assigning the value to sum
let difference = num1 - num2 //subtracting num2 from num1 and assigning the value to difference
let product = num1 * num2 //multiplying num1 and num2 and assigning the value to product
let quotient = num1 / num2 //dividing num1 by num2 and assigning the value to quotient
let modulus = num1%num2 //modulus of num1 and num2 and assigning the value to modulus

console.log(`Sum: ${sum}`)  //printing the value of sum
console.log(`Difference: ${difference}`)  //printing the value of difference
console.log(`Product: ${product}`)  //printing the value of product
console.log(`Quotient: ${quotient}`)  //printing the value of quotient
console.log(`Modulus: ${modulus}`)  //printing the value of modulus

let isEqual = num1 == num2 //checking if num1 is equal to num2
let isGreater = num1 > num2 //checking if num1 is greater than num2
let isLess = num1 < num2 //checking if num1 is less than num2
let isNotEqual = num1 != num2 //checking if num1 is not equal to num2

console.log(`isEqual is: ${isEqual}`)   //printing the value of isEqual
console.log(`isGreater is: ${isGreater}`)   //printing the value of isGreater
console.log(`isLess is: ${isLess}`)     //printing the value of isLess
console.log(`isNotEqual is: ${isNotEqual}`)     //printing the value of isNotEqual

let And = num1 > 0 && num2 > 0 //checking if both num1 and num2 are greater than 0
let Or = num1 > 0 || num2 < 0 //checking if either num1 is greater than 0 or num2 is less than 0
let Not = !(num1 > 0) //checking if num1 is not greater than 0

console.log(`And is: ${And}`)   //printing the value of And
console.log(`Or is: ${Or}`)     //printing the value of Or
console.log(`Not is: ${Not}`)   //printing the value of Not